CREATE TABLE persons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  first_name VARCHAR(80) NOT NULL,
  last_name VARCHAR(80) NOT NULL,
  rfid_uid VARCHAR(20) NOT NULL UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE presence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id BIGINT NOT NULL REFERENCES persons(id),
  presence_date DATE NOT NULL,
  period VARCHAR(16) NOT NULL CHECK (period IN ('MORNING', 'AFTERNOON')),
  check_in TIMESTAMP WITH TIME ZONE NOT NULL,
  check_out TIMESTAMP WITH TIME ZONE,
  status VARCHAR(24) CHECK (status IN ('PRESENT', 'LATE', 'EARLY_EXIT')),
  CONSTRAINT presence_one_per_period UNIQUE (person_id, presence_date, period),
  CONSTRAINT presence_ordered_times CHECK (check_out IS NULL OR check_out >= check_in)
);

CREATE INDEX presence_date_idx ON presence(presence_date);

CREATE TABLE scan_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(80) NOT NULL,
  device_id VARCHAR(64) NOT NULL,
  card_uid VARCHAR(20) NOT NULL,
  person_id BIGINT,
  received_at TIMESTAMP WITH TIME ZONE NOT NULL,
  action VARCHAR(32) NOT NULL,
  result VARCHAR(24) NOT NULL,
  CONSTRAINT scan_event_unique UNIQUE (device_id, event_id)
);

CREATE INDEX scan_person_idx ON scan_events(person_id);
CREATE INDEX scan_card_idx ON scan_events(card_uid);
CREATE INDEX scan_received_idx ON scan_events(received_at DESC);
